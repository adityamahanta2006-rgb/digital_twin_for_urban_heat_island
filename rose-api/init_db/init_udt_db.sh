#!/usr/bin/env bash
set -e

psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<-EOSQL
	CREATE USER "$UDTDB_USER" WITH PASSWORD '$UDTDB_PASSWORD';
	ALTER USER "$UDTDB_USER" WITH SUPERUSER;
	CREATE DATABASE "$UDTDB_DB";
	GRANT ALL PRIVILEGES ON DATABASE "$UDTDB_DB" TO "$UDTDB_USER";
	ALTER DATABASE "$UDTDB_DB" OWNER TO "$UDTDB_USER";

EOSQL

psql -v ON_ERROR_STOP=1 --username "$UDTDB_USER" --dbname "$UDTDB_DB" <<-EOSQL
	CREATE EXTENSION postgis;
EOSQL